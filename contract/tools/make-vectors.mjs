// Builds contract/vectors/*.json and contract/vectors/index.json.
//
// The reference generates, and a person states. Every case in
// contract/tools/vectors/<family>.cases.mjs carries a hand-written partial
// `want`; the full `expect` written to disk is what the family's reference
// returns for the case's input, and generation stops when the two disagree on
// any key the person wrote down. A vector produced by the code alone would only
// prove the code agrees with itself, and a table typed by hand alone would drift
// from the code the first time nobody re-ran it; the pair is what makes a vector
// worth porting four times.
//
// Nothing is written here: buildVectors() returns the files as text, and
// generate.mjs decides whether to write them or to compare them.

import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { documentText } from './documents.mjs';
import { hashVectors } from './make-hash-vectors.mjs';
import { CASE_MODULES, HASH_FAMILY } from './vectors/families.mjs';

const CONTRACT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

export const CONSUMERS = Object.freeze(['agent', 'mac', 'desktop', 'android']);

const GENERATED = 'Generated by node contract/tools/generate.mjs. Edit contract/tools, not these files.';
const CASE_NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

// References are imported by the path the index will name, relative to
// contract/, so that the module a case is checked against here is the module
// validate.mjs runs later and nothing else.
const REFERENCES = new Map();
for (const module of CASE_MODULES) {
  if (!REFERENCES.has(module.reference)) {
    REFERENCES.set(module.reference, await import(pathToFileURL(path.join(CONTRACT, module.reference)).href));
  }
}

/** JSON equality: objects by key set in any order, arrays element by element, everything else by identity. */
function sameJson(a, b) {
  if (a === b) return true;
  if (typeof a !== 'object' || typeof b !== 'object' || a === null || b === null) return false;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  if (Array.isArray(a)) return a.length === b.length && a.every((item, index) => sameJson(item, b[index]));
  const keys = Object.keys(a);
  if (keys.length !== Object.keys(b).length) return false;
  return keys.every((key) => Object.hasOwn(b, key) && sameJson(a[key], b[key]));
}

/** Every number anywhere in `value` that a 53-bit integer cannot hold exactly, as `path: value`. */
function unsafeNumbers(value, at, found = []) {
  if (typeof value === 'number' && !Number.isSafeInteger(value)) found.push(`${at}: ${value}`);
  else if (Array.isArray(value)) value.forEach((item, index) => unsafeNumbers(item, `${at}[${index}]`, found));
  else if (value !== null && typeof value === 'object') {
    for (const [key, child] of Object.entries(value)) unsafeNumbers(child, `${at}.${key}`, found);
  }
  return found;
}

/** Per consumer, how many of these cases list it, in the fixed consumer order and without zeros. */
function countConsumers(cases) {
  const counts = {};
  for (const consumer of CONSUMERS) {
    const count = cases.filter((entry) => entry.consumers.includes(consumer)).length;
    if (count > 0) counts[consumer] = count;
  }
  return counts;
}

function buildCase(module, group, entry, names) {
  const where = `${module.family}/${group}/${entry.name ?? '<unnamed>'}`;
  if (typeof entry.name !== 'string' || !CASE_NAME.test(entry.name)) {
    throw new Error(`${where}: a case name is lower-case words joined by single hyphens`);
  }
  // 1. Names are unique across the whole family, not just the group: a client
  //    report that says "outcome/accepted failed" must point at one case.
  if (names.has(entry.name)) throw new Error(`${where}: the name ${entry.name} is used twice in the family`);
  names.add(entry.name);

  // 2. A case with nothing stated by hand is a case nobody checked.
  const { want } = entry;
  if (want === null || typeof want !== 'object' || Array.isArray(want) || Object.keys(want).length === 0) {
    throw new Error(`${where}: want is missing or empty; state at least one expected key by hand`);
  }

  const input = typeof entry.input === 'function' ? entry.input() : entry.input;
  // An input written to disk has to be self-contained JSON. A key holding
  // undefined would vanish on the way out and the vector would test something
  // other than what the case says.
  if (!sameJson(JSON.parse(JSON.stringify(input)), input)) {
    throw new Error(`${where}: the input does not survive JSON; it must be plain data`);
  }

  // 3. The reference produces the full expectation, from a copy so a reference
  //    that mutates its argument cannot change what is written as the input.
  const expect = REFERENCES.get(module.reference).run(group, structuredClone(input));

  // 4. Every key a person stated must be what the reference says.
  for (const [key, value] of Object.entries(want)) {
    if (!Object.hasOwn(expect, key)) {
      throw new Error(`${where}: want disagrees with ${module.reference}: it states "${key}", which the reference does not return`);
    }
    if (!sameJson(value, expect[key])) {
      throw new Error(`${where}: want disagrees with ${module.reference} on "${key}": stated ${JSON.stringify(value)}, the reference gives ${JSON.stringify(expect[key])}`);
    }
  }

  // 5. Numbers in an expectation are compared as integers by four languages;
  //    anything a double cannot hold exactly would compare differently in each.
  const unsafe = unsafeNumbers(expect, 'expect');
  if (unsafe.length > 0) throw new Error(`${where}: not a safe integer in ${unsafe.join(', ')}`);

  // 6. The case as clients read it.
  return {
    name: entry.name,
    purpose: entry.purpose,
    consumers: entry.consumers ?? module.consumers[group],
    tags: entry.tags ?? [],
    input,
    expect,
  };
}

function buildFamily(module) {
  for (const key of ['family', 'section', 'reference']) {
    if (typeof module[key] !== 'string') throw new Error(`a case module has no ${key}`);
  }
  if (!REFERENCES.get(module.reference).FAMILIES?.includes(module.family)) {
    throw new Error(`${module.reference} does not list ${module.family} in FAMILIES`);
  }
  const names = new Set();
  const groups = {};
  const entries = [];
  for (const [group, cases] of Object.entries(module.groups)) {
    if (!Array.isArray(module.consumers?.[group])) throw new Error(`${module.family}/${group}: no consumers are named for the group`);
    groups[group] = cases.map((entry) => buildCase(module, group, entry, names));
    entries.push({ group, cases: groups[group].length, consumers: countConsumers(groups[group]) });
  }
  const file = {
    $schema: `../schemas/${module.family}-vectors.schema.json`,
    $comment: GENERATED,
    family: module.family,
    contract: 3,
    section: module.section,
    reference: module.reference,
    notes: module.notes ?? [],
    groups,
  };
  const entry = {
    family: module.family,
    file: `vectors/${module.family}.json`,
    schema: `${module.family}-vectors.schema.json`,
    layout: 'groups',
    section: module.section,
    reference: module.reference,
    generator: `tools/vectors/${module.family}.cases.mjs`,
    groups: entries,
  };
  return { file, entry };
}

/** The index entry of the flat hash family, counted from the vectors make-hash-vectors.mjs builds. */
function hashEntry() {
  const count = hashVectors().length;
  const consumers = {};
  for (const consumer of HASH_FAMILY.consumers) consumers[consumer] = count;
  return {
    family: HASH_FAMILY.family,
    file: HASH_FAMILY.file,
    schema: HASH_FAMILY.schema,
    layout: HASH_FAMILY.layout,
    section: HASH_FAMILY.section,
    reference: HASH_FAMILY.reference,
    generator: HASH_FAMILY.generator,
    groups: [{ group: HASH_FAMILY.group, cases: count, consumers }],
  };
}

/**
 * Every vector family file plus vectors/index.json, as a Map from the path
 * relative to contract/ to the exact text that belongs there.
 */
export function buildVectors() {
  const files = new Map();
  const families = [hashEntry()];
  const seen = new Set([HASH_FAMILY.family]);
  for (const module of CASE_MODULES) {
    if (seen.has(module.family)) throw new Error(`the family ${module.family} is listed twice in vectors/families.mjs`);
    seen.add(module.family);
    const { file, entry } = buildFamily(module);
    files.set(entry.file, documentText(file));
    families.push(entry);
  }
  const index = {
    $schema: '../schemas/vector-index.schema.json',
    $comment: GENERATED,
    contract: 3,
    loading: 'Read this file first. Paths are relative to contract/. Run every group that lists you as a consumer, with exactly one adapter per group, and fail if a file is missing or if you ran a different number of cases than consumers.<you> says.',
    comparison: 'Objects by key set in any order; arrays element by element; strings by code point; booleans and null by identity; numbers in expect are integers. Every expect key is present. A field named *Text is a JSON document: compare parsed, object key order ignored, number lexemes exact.',
    families,
  };
  files.set('vectors/index.json', documentText(index));
  return files;
}
