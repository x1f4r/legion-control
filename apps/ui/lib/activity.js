const POWER_TITLES = {
  'power.restart': 'Restart',
  'power.shutdown': 'Shut down',
  'power.sleep': 'Sleep',
  'power.wake': 'Wake',
  'power.switch': 'Switch system',
  'power.cancel': 'Cancel power action',
  restart: 'Restart',
  shutdown: 'Shut down',
  sleep: 'Sleep',
  wake: 'Wake',
};

function capitalize(word) {
  const s = String(word || '').trim();
  if (!s) return '';
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/**
 * Turns a job or activity record into a plain human title without exposing raw shell commands.
 */
export function friendlyJobName(job) {
  if (!job || typeof job !== 'object') return 'Command';

  if (job.kind === 'transfer' && typeof job.title === 'string' && job.title.trim()) {
    return job.title.trim();
  }

  if (job.project && job.task) {
    return `${capitalize(job.task)} for ${job.project}`;
  }

  const toolKey = String(job.tool || job.action || '').toLowerCase();
  if (POWER_TITLES[toolKey]) {
    return POWER_TITLES[toolKey];
  }

  const rawName = typeof job.name === 'string' ? job.name.trim() : '';
  if (rawName) {
    // Project tasks named like "proj:website:tests" -> "Tests for website"
    const projMatch = rawName.match(/^proj:([^:]+):(.+)$/i);
    if (projMatch) {
      return `${capitalize(projMatch[2])} for ${projMatch[1]}`;
    }
    const lower = rawName.toLowerCase();
    if (lower.startsWith('power.') && POWER_TITLES[lower]) {
      return POWER_TITLES[lower];
    }
    // Check whether the node auto-filled `name` from the command's program name.
    const cmd = typeof job.command === 'string' ? job.command.trim() : '';
    const firstToken = cmd.split(/\s+/)[0] || '';
    const baseToken = firstToken.replace(/^.*[/\\]/, '').toLowerCase();
    const baseName = rawName.replace(/^.*[/\\]/, '').toLowerCase();
    const looksAutoGenerated =
      !rawName.includes(' ') &&
      (SHELL_NAMES.has(baseName) || (baseToken && baseName === baseToken && rawName === rawName.toLowerCase()));
    if (!looksAutoGenerated) {
      return rawName;
    }
  }

  return 'Command';
}

/**
 * Returns the one-word plain state or technical exit code for an activity row.
 */
export function friendlyJobState(job, technical = false) {
  const state = String(job?.state || '').toLowerCase();
  if (state === 'running' || state === 'starting') {
    return { label: 'Running', cls: 'running' };
  }
  if (technical) {
    if (job?.exit_code != null && Number.isInteger(job.exit_code)) {
      return {
        label: `exit ${job.exit_code}`,
        cls: state === 'failed' || job.exit_code !== 0 ? 'failed' : 'done',
      };
    }
    if (state === 'succeeded') return { label: 'exit 0', cls: 'done' };
    if (state === 'failed') return { label: 'failed', cls: 'failed' };
    if (state === 'cancelled') return { label: 'cancelled', cls: '' };
    if (state === 'interrupted') return { label: 'interrupted', cls: '' };
    return { label: state || 'done', cls: 'done' };
  }

  if (state === 'succeeded') return { label: 'Finished', cls: 'done' };
  if (state === 'failed') return { label: 'Failed', cls: 'failed' };
  if (state === 'cancelled') return { label: 'Stopped', cls: '' };
  if (state === 'interrupted') return { label: 'Interrupted', cls: '' };
  return { label: 'Finished', cls: 'done' };
}

/**
 * Formats a duration in plain English ("took 3 seconds", "took 2 minutes") or concise technical form.
 */
export function formatActivityDuration(seconds, technical = false) {
  if (!Number.isFinite(seconds) || seconds < 0) return '';
  if (technical) {
    if (seconds < 60) {
      return seconds < 10 ? `${seconds.toFixed(1)} s` : `${Math.round(seconds)} s`;
    }
    const mins = Math.floor(seconds / 60);
    const rem = Math.round(seconds % 60);
    if (mins < 60) return rem > 0 ? `${mins} min ${rem} s` : `${mins} min`;
    return formatDuration(seconds);
  }
  const rounded = Math.round(seconds);
  if (rounded < 1) return 'took under a second';
  if (rounded < 60) return `took ${rounded} ${rounded === 1 ? 'second' : 'seconds'}`;
  const mins = Math.round(seconds / 60);
  if (mins < 60) return `took ${mins} ${mins === 1 ? 'minute' : 'minutes'}`;
  const hours = Math.round(seconds / 3600);
  if (hours < 24) return `took ${hours} ${hours === 1 ? 'hour' : 'hours'}`;
  const days = Math.round(seconds / 86400);
  return `took ${days} ${days === 1 ? 'day' : 'days'}`;
}

export function formatFriendlyRelativeTime(value, nowMs = Date.now()) {
  if (!value) return '';
  const ts = typeof value === 'number' ? value : Date.parse(value);
  if (!Number.isFinite(ts)) return '';
  const diffSec = Math.max(0, Math.floor((nowMs - ts) / 1000));
  if (diffSec < 45) return 'just now';
  if (diffSec < 3600) {
    const mins = Math.max(1, Math.round(diffSec / 60));
    return `${mins} ${mins === 1 ? 'minute' : 'minutes'} ago`;
  }
  if (diffSec < 86400) {
    const hours = Math.round(diffSec / 3600);
    return `${hours} ${hours === 1 ? 'hour' : 'hours'} ago`;
  }
  const days = Math.round(diffSec / 86400);
  return days === 1 ? '1 day ago' : `${days} days ago`;
}

export function jobDurationSeconds(job) {
  if (typeof job?.duration_s === 'number' && Number.isFinite(job.duration_s)) {
    return job.duration_s;
  }
  if (job?.created && job?.finished) {
    const start = Date.parse(job.created);
    const end = Date.parse(job.finished);
    if (Number.isFinite(start) && Number.isFinite(end) && end >= start) {
      return (end - start) / 1000;
    }
  }
  return null;
}

export function formatActivitySubtitle(job, { includeMachine = true, technical = false, nowMs = Date.now() } = {}) {
  const parts = [];
  if (includeMachine && job.machine) parts.push(job.machine);

  const active = job.state === 'running' || job.state === 'starting';
  if (active) {
    if (job.created) {
      const ago = formatFriendlyRelativeTime(job.created, nowMs);
      if (ago) parts.push(includeMachine ? `started ${ago}` : `Started ${ago}`);
    }
  } else {
    const when = job.finished || job.created;
    if (when) {
      const ago = formatFriendlyRelativeTime(when, nowMs);
      if (ago) parts.push(includeMachine ? ago : capitalize(ago));
    }
    if (job.actor && !jobDurationSeconds(job)) {
      parts.push(`by ${job.actor}`);
    } else if (job.state !== 'cancelled' && job.state !== 'interrupted') {
      const dur = jobDurationSeconds(job);
      if (dur != null) {
        const durText = formatActivityDuration(dur, technical);
        if (durText) parts.push(durText);
      }
    }
  }

  return parts.join(' · ');
}

function startOfLocalDay(ms) {
  const d = new Date(ms);
  d.setHours(0, 0, 0, 0);
  return d.getTime();
}

/**
 * Groups activity entries into Running now, Today, Yesterday, and Earlier.
 */
export function groupActivity(items, nowMs = Date.now()) {
  const running = [];
  const today = [];
  const yesterday = [];
  const earlier = [];

  const todayStart = startOfLocalDay(nowMs);
  const yesterdayStart = todayStart - 86_400_000;

  for (const item of items || []) {
    const active = item.state === 'running' || item.state === 'starting';
    if (active) {
      running.push(item);
      continue;
    }
    const ts = Date.parse(item.finished || item.created || '');
    if (!Number.isFinite(ts) || ts >= todayStart) {
      today.push(item);
    } else if (ts >= yesterdayStart) {
      yesterday.push(item);
    } else {
      earlier.push(item);
    }
  }

  const byRecent = (a, b) =>
    String(b.finished || b.created || '').localeCompare(String(a.finished || a.created || ''));
  running.sort((a, b) => String(b.created || '').localeCompare(String(a.created || '')));
  today.sort(byRecent);
  yesterday.sort(byRecent);
  earlier.sort(byRecent);

  const groups = [];
  if (running.length > 0) groups.push({ key: 'running', label: 'Running now', items: running });
  if (today.length > 0) groups.push({ key: 'today', label: 'Today', items: today });
  if (yesterday.length > 0) groups.push({ key: 'yesterday', label: 'Yesterday', items: yesterday });
  if (earlier.length > 0) groups.push({ key: 'earlier', label: 'Earlier', items: earlier });
  return groups;
}

/**
 * Plain-word status phrase for a machine card header ("Idle", "Busy · 2 things running", "Busy · agents").
 */
export function formatMachineStatusPhrase(machine, nowMs = Date.now(), { wakePending = false } = {}) {
  if (!machine) return '';
  if (machine.status === 'asking' || machine.asking) {
    return 'Checking…';
  }
  if (!machine.reachable) {
    if (wakePending) return 'Wake sent · waiting for it to answer';
    if (machine.lastSeenAt) {
      const seen = formatRelativeTime(machine.lastSeenAt, nowMs);
      if (seen) return `Last on ${seen}`;
    }
    return 'Off';
  }
  if (machine.runningJobs > 0) {
    return `Busy · ${machine.runningJobs} ${machine.runningJobs === 1 ? 'thing' : 'things'} running`;
  }
  if (machine.busy && Array.isArray(machine.busyReasons) && machine.busyReasons.length > 0) {
    const labels = machine.busyReasons.map(busyReasonLabel).filter(Boolean);
    if (labels.length === 1) return `Busy · ${labels[0]}`;
    if (labels.length > 1) return `Busy · ${labels[0]} +${labels.length - 1}`;
  }
  if (machine.busy) return 'Busy';
  return 'Idle';
}

/**
 * Plain-word subtitle for a machine's own detail header ("Busy · on for 11 hours", "Idle · on for 41 days").
 */
export function formatMachineDetailSubtitle(machine, nowMs = Date.now(), { wakePending = false } = {}) {
  if (!machine) return '';
  if (machine.status === 'asking' || machine.asking) return 'Checking…';
  if (!machine.reachable) {
    if (wakePending) return 'Wake sent · waiting for it to answer';
    if (machine.lastSeenAt) {
      const seen = formatRelativeTime(machine.lastSeenAt, nowMs);
      if (seen) return `Off · last on ${seen}`;
    }
    return 'Off';
  }
  const lead = machine.busy ? 'Busy' : 'Idle';
  if (machine.sys?.uptime_s != null) {
    const up = formatFriendlyUptime(machine.sys.uptime_s);
    if (up) return `${lead} · on for ${up}`;
  }
  return lead;
}

export function formatFriendlyUptime(seconds) {
  if (!Number.isFinite(seconds) || seconds < 0) return '';
  const total = Math.floor(seconds);
  if (total < 60) return `${total} ${total === 1 ? 'second' : 'seconds'}`;
  const days = Math.floor(total / 86400);
  const hours = Math.floor((total % 86400) / 3600);
  const mins = Math.floor((total % 3600) / 60);
  if (days >= 2) return `${days} days`;
  if (days === 1) return hours > 0 ? `1 day ${hours} ${hours === 1 ? 'hour' : 'hours'}` : '1 day';
  if (hours > 0) return `${hours} ${hours === 1 ? 'hour' : 'hours'}`;
  return `${mins} ${mins === 1 ? 'minute' : 'minutes'}`;
}

/**
 * Plain subtitle for the Machines screen header ("3 are on, 1 is off").
 */
export function formatMachinesHeaderSubtitle(machines, { cachedAt = null, nowMs = Date.now() } = {}) {
  const list = Array.isArray(machines) ? machines : [];
  if (list.length === 0) return '';
  const on = list.filter((m) => m.reachable).length;
  const asking = list.filter((m) => m.status === 'asking' || m.asking).length;
  const off = list.length - on - asking;

  const parts = [];
  if (on > 0) parts.push(`${on} ${on === 1 ? 'is' : 'are'} on`);
  if (off > 0) parts.push(`${off} ${off === 1 ? 'is' : 'are'} off`);
  if (asking > 0) parts.push(on === 0 && off === 0 ? 'Checking machines…' : `checking ${asking}`);

  let text = parts.join(', ');
  if (cachedAt) {
    const asOf = formatRelativeTime(cachedAt, nowMs);
    if (asOf) text = text ? `${text} · as of ${asOf}` : `As of ${asOf}`;
  }
  return text;
}

/**
 * Plain-language summary of what a device's role allows, for Settings and Connections.
 */
export function describePlainPermissions(whoami, tools = []) {
  const allowed = Array.isArray(whoami?.tools) ? new Set(whoami.tools) : null;
  if (!allowed) {
    if (whoami?.role === 'owner') return 'May do everything';
    if (whoami?.role === 'observer') return 'Look only';
    return 'Connected';
  }
  const effectSet = new Set();
  for (const t of tools || []) {
    if (allowed.has(t.name) && t.effect) effectSet.add(t.effect);
  }
  const hasAdmin = effectSet.has('admin') || whoami?.role === 'owner';
  const hasPower = effectSet.has('power');
  const hasExec = effectSet.has('exec');
  const hasWrite = effectSet.has('write');
  const hasDestroy = effectSet.has('destroy');
  const hasRead = effectSet.has('read') || allowed.size > 0;

  if (hasAdmin && hasPower && hasExec && hasWrite) {
    return 'May do everything';
  }
  if (!hasAdmin && hasPower && hasExec && hasWrite) {
    return 'May do everything except change permissions';
  }
  if (!hasAdmin && !hasPower && !hasExec && !hasWrite && !hasDestroy && hasRead) {
    return 'Look only';
  }
  const caps = [];
  if (hasRead) caps.push('look');
  if (hasWrite) caps.push('edit files');
  if (hasExec) caps.push('run commands');
  if (hasPower) caps.push('control power');
  if (hasAdmin) caps.push('change permissions');
  if (caps.length === 0) return 'No actions allowed';
  if (caps.length === 1) return `May ${caps[0]}`;
  return `May ${caps.slice(0, -1).join(', ')} and ${caps[caps.length - 1]}`;
}

export function formatCommandMeta(entry, technical = false) {
  const dur = entry.durationMs != null ? formatDurationMs(entry.durationMs) : '';
  if (technical) {
    const code = entry.exitCode != null ? `exit ${entry.exitCode}` : entry.status || '';
    return [code, dur].filter(Boolean).join(' · ');
  }
  const word =
    entry.status === 'running'
      ? 'Running…'
      : entry.exitCode === 0
        ? 'Finished'
        : entry.exitCode != null
          ? 'Failed'
          : entry.status === 'cancelled'
            ? 'Stopped'
            : 'Finished';
  return [word, dur].filter(Boolean).join(' · ');
}

/**
 * One plain-English sentence describing what a dry-run power or destructive action would do.
 */
export function describeDryRunSummary(tool, target, args = {}) {
  const name = args?.machine || target || 'this machine';
  const into = args?.into ? capitalize(args.into) : '';
  switch (tool) {
    case 'power.sleep':
      return `${name} would go to sleep.`;
    case 'power.restart':
      return into ? `${name} would restart into ${into}.` : `${name} would restart.`;
    case 'power.shutdown':
      return `${name} would switch off.`;
    case 'power.wake':
      return `A wake signal would be sent to ${name}.`;
    case 'power.switch':
      return into ? `${name} would switch to ${into}.` : `${name} would switch systems.`;
    case 'power.cancel':
      return `Any pending power action on ${name} would be cancelled.`;
    default:
      return `Ready to run on ${name}.`;
  }
}

/**
 * Splits a refusal (such as `dryResult.would_refuse`) into a plain first sentence and full details
 * suitable for a collapsed "More" disclosure.
 */
export function plainRefusalParts(refusal) {
  if (!refusal) return { first: '', detailMessage: '', detailHint: '' };
  const rawMessage = typeof refusal === 'string' ? refusal : String(refusal.message || '');
  const rawHint = typeof refusal === 'object' && refusal.hint ? String(refusal.hint) : '';
  const { first, rest } = splitFirstSentence(rawMessage);

  let plainFirst = first;
  if (/node\.toml\s+does not say what keeps this machine busy/i.test(rawMessage)) {
    plainFirst = 'this machine does not have a busy check set up yet.';
  } else {
    plainFirst = first.replace(/^Refused to [^:]+:\s*/i, '').trim() || first;
  }

  const hasExtra = Boolean(rest || rawHint || plainFirst !== rawMessage.trim());
  return {
    first: plainFirst,
    detailMessage: hasExtra ? rawMessage.trim() : '',
    detailHint: rawHint.trim(),
  };
}

/**
 * Plain-English description of what a named role is allowed to do (for invite confirmations).
 */
export function describeRolePlain(role) {
  const lower = String(role || '').trim().toLowerCase();
  if (lower === 'owner') return 'do everything on this machine';
  if (lower === 'operator') return 'do everything except change permissions';
  if (lower === 'editor') return 'look at machines and edit files';
  if (lower === 'observer') return 'look only';
  return 'use this machine with that identity';
}

export function formatInviteValidity(minutes) {
  const m = Number(minutes);
  if (!Number.isFinite(m) || m <= 0) return '15 minutes';
  if (m === 60) return '1 hour';
  if (m === 1440) return '1 day';
  if (m % 1440 === 0) return `${m / 1440} days`;
  if (m % 60 === 0) return `${m / 60} hours`;
  return m === 1 ? '1 minute' : `${m} minutes`;
}

/**
 * Progress percentage (0..100) for a machine transfer job or device transfer.
 */
export function transferProgressPct(progressOrTransfer) {
  if (!progressOrTransfer || typeof progressOrTransfer !== 'object') return null;
  const done = Number(progressOrTransfer.bytes_done);
  const total = Number(progressOrTransfer.bytes_total);
  if (!Number.isFinite(done) || !Number.isFinite(total) || total <= 0) return null;
  return clampPct((done / total) * 100);
}

/**
 * Plain-English remaining time estimate for an active transfer ("about 1 minute left").
 */
export function formatTransferEta(bytesDone, bytesTotal, rate) {
  if (!Number.isFinite(bytesDone) || !Number.isFinite(bytesTotal) || !Number.isFinite(rate) || rate <= 0) {
    return '';
  }
  const remaining = Math.max(0, bytesTotal - bytesDone);
  if (remaining <= 0) return '';
  const sec = Math.ceil(remaining / rate);
  if (sec < 45) return `about ${Math.max(1, sec)} seconds left`;
  const mins = Math.round(sec / 60);
  if (mins < 60) return `about ${mins} ${mins === 1 ? 'minute' : 'minutes'} left`;
  const hours = Math.round(sec / 3600);
  return `about ${hours} ${hours === 1 ? 'hour' : 'hours'} left`;
}

/**
 * Formats the subtitle for a machine-side transfer job (`kind === 'transfer'`).
 */
export function formatTransferJobSubtitle(job, { includeMachine = true, technical = false, nowMs = Date.now() } = {}) {
  if (!job) return '';
  const active = job.state === 'running' || job.state === 'starting';
  const p = job.progress;

  if (active && p && Number.isFinite(p.bytes_total) && p.bytes_total > 0) {
    const parts = [];
    if (includeMachine && job.machine) parts.push(job.machine);
    parts.push(
      technical
        ? `${formatBytes(p.bytes_done || 0)} / ${formatBytes(p.bytes_total)} (${p.bytes_done || 0} / ${p.bytes_total} B)`
        : formatBytePair(p.bytes_done || 0, p.bytes_total),
    );
    const eta = formatTransferEta(p.bytes_done || 0, p.bytes_total, p.rate);
    if (eta) parts.push(eta);
    return parts.join(' · ');
  }

  if (job.state === 'failed' && job.error_summary && !technical) {
    return job.error_summary;
  }

  const parts = [];
  if (includeMachine && job.machine) {
    parts.push(technical ? job.machine : `From ${job.machine}`);
  }
  const when = job.finished || job.created;
  if (when) {
    const ago = formatFriendlyRelativeTime(when, nowMs);
    if (ago) parts.push(ago);
  }
  const dur = jobDurationSeconds(job);
  if (dur != null && job.state !== 'cancelled' && job.state !== 'failed') {
    const durText = formatActivityDuration(dur, technical);
    if (durText) parts.push(durText);
  }
  if (technical && job.from && job.to) {
    parts.push(`${job.from} -> ${job.to}`);
  }
  return parts.join(' · ');
}

/**
 * Plain title for a device-side transfer ("Downloading Beach.mp4", "Downloaded Tickets.pdf", "Uploading Photo.jpg").
 */
export function formatDeviceTransferTitle(transfer, technical = false) {
  if (!transfer) return 'Transfer';
  const name = transfer.name || 'file';
  const isUp = transfer.direction === 'upload';
  if (technical) {
    return isUp ? `upload ${name} -> ${transfer.machine}:${transfer.path}` : `download ${transfer.machine}:${transfer.path}`;
  }
  if (transfer.state === 'done') {
    return isUp ? `Uploaded ${name}` : `Downloaded ${name}`;
  }
  if (transfer.state === 'cancelling') {
    return `Cancelling ${name}`;
  }
  if (transfer.state === 'queued') {
    return isUp ? `Waiting to upload ${name}` : `Waiting to download ${name}`;
  }
  return isUp ? `Uploading ${name} to ${transfer.machine}` : `Downloading ${name}`;
}

/**
 * Plain or technical subtitle for a device-side transfer row.
 */
export function formatDeviceTransferSubtitle(transfer, { deviceNoun = 'phone', technical = false, nowMs = Date.now() } = {}) {
  if (!transfer) return '';
  const isUp = transfer.direction === 'upload';
  const destLabel = isUp ? `From this ${deviceNoun} to ${transfer.machine}` : `To this ${deviceNoun}`;

  if (transfer.state === 'cancelling') {
    const fallback = 'Removing partial files…';
    if (!transfer.error) return fallback;
    const errObj =
      typeof transfer.error === 'object'
        ? { ...transfer.error, machine: transfer.error.machine || transfer.machine || null }
        : transfer.error;
    return plainErrorMessage(errObj, fallback, { technical, deviceNoun });
  }

  if (transfer.state === 'running' || transfer.state === 'paused' || transfer.state === 'queued') {
    const parts = [transfer.state === 'paused' ? 'Paused' : destLabel];
    if (Number.isFinite(transfer.bytes_total) && transfer.bytes_total > 0) {
      parts.push(
        technical
          ? `${transfer.bytes_done || 0} / ${transfer.bytes_total} B`
          : formatBytePair(transfer.bytes_done || 0, transfer.bytes_total),
      );
    }
    if (transfer.state === 'running') {
      const eta = formatTransferEta(transfer.bytes_done || 0, transfer.bytes_total, transfer.rate);
      if (eta) parts.push(eta);
    }
    return parts.join(' · ');
  }

  if (transfer.state === 'failed') {
    const fallback = 'Stopped before finishing. Tap Resume to continue from where it stopped.';
    const errObj =
      transfer.error && typeof transfer.error === 'object'
        ? { ...transfer.error, machine: transfer.error.machine || transfer.machine || null }
        : transfer.error;
    return plainErrorMessage(errObj, fallback, { technical, deviceNoun });
  }

  if (transfer.state === 'done') {
    if (technical) {
      return [
        transfer.localPath || destLabel,
        transfer.bytes_total ? `${transfer.bytes_total} B` : null,
        transfer.hash ? transfer.hash.slice(0, 22) : null,
      ]
        .filter(Boolean)
        .join(' · ');
    }
    if (!isUp && transfer.canOpen) {
      return `${destLabel} · tap to open`;
    }
    const when = transfer.finished ? formatFriendlyRelativeTime(transfer.finished, nowMs) : '';
    return [destLabel, when].filter(Boolean).join(' · ');
  }

  const when = transfer.finished || transfer.created;
  return [destLabel, when ? formatFriendlyRelativeTime(when, nowMs) : null].filter(Boolean).join(' · ');
}

/**
 * State badge for a device-side transfer row.
 */
export function friendlyDeviceTransferState(transfer, technical = false) {
  const st = transfer?.state || '';
  if (st === 'running') {
    const pct = transferProgressPct(transfer);
    return { label: pct != null ? `${pct}%` : 'Running', cls: 'running' };
  }
  if (st === 'queued') return { label: 'Queued', cls: 'running' };
  if (st === 'paused') return { label: 'Paused', cls: '' };
  if (st === 'cancelling') {
    return {
      label: technical ? 'cancelling' : 'Cancelling',
      cls: transfer?.error ? 'failed' : '',
    };
  }
  if (st === 'done') return { label: technical ? 'done' : 'Finished', cls: 'done' };
  if (st === 'failed') return { label: technical ? 'failed' : 'Stopped', cls: 'failed' };
  if (st === 'cancelled') return { label: technical ? 'cancelled' : 'Stopped', cls: '' };
  return { label: st || 'Finished', cls: 'done' };
}
