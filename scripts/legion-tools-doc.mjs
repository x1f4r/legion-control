#!/usr/bin/env node
// Generate or check docs/legion/tools.md from a built `legion` binary's `tools --json` output.
//
//   node scripts/legion-tools-doc.mjs                    regenerate docs/legion/tools.md
//   node scripts/legion-tools-doc.mjs --check            exit non-zero if docs/legion/tools.md differs
//   node scripts/legion-tools-doc.mjs --bin <path>       use a specific legion binary
//   node scripts/legion-tools-doc.mjs --out <path>       write or check another file
//
// The binary is run under a fresh empty LEGION_HOME so user extensions in tools.d/ never leak into
// the reference. Text above the generated marker in docs/legion/tools.md is kept as written.
//
// scripts/check.sh and CI run it with --check.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const MARKER = '<!-- Generated by scripts/legion-tools-doc.mjs; do not edit below this line. -->';

const DEFAULT_OUT = path.join(repository, 'docs', 'legion', 'tools.md');

const DEFAULT_INTRO = `# Tool reference

Every operation Legion performs is a tool with a name, an effect, and a JSON Schema for its
arguments. The command line, MCP, HTTP, and RPC doors expose the same registry, so a tool listed
here behaves identically through every door.

Run \`legion tools\` on any machine to see its live registry (including any local extensions in
\`tools.d/\`), or \`legion help <tool>\` for one tool's schema.

${MARKER}
`;

/**
 * Locate a built `legion` binary under `target/` when `--bin` was not given.
 * When both release and debug binaries exist, the newer one is chosen.
 */
export function resolveBinary(root = repository, explicit = null) {
  const exe = process.platform === 'win32' ? '.exe' : '';
  if (explicit) {
    const candidate = path.resolve(explicit);
    if (fs.existsSync(candidate)) return candidate;
    if (exe && !candidate.toLowerCase().endsWith(exe) && fs.existsSync(candidate + exe)) {
      return candidate + exe;
    }
    throw new Error(`legion binary not found at ${explicit}.`);
  }
  const candidates = [
    path.join(root, 'target', 'release', `legion${exe}`),
    path.join(root, 'target', 'debug', `legion${exe}`),
  ].filter(file => fs.existsSync(file));
  if (candidates.length === 0) {
    throw new Error('No built legion binary found under target/release or target/debug. Build it first (for example `cargo build -p legion-cli`) or pass --bin <path>.');
  }
  candidates.sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs);
  return candidates[0];
}

/**
 * Invoke `<binary> tools --json` inside an isolated empty LEGION_HOME and return the parsed tool specs.
 */
export function readToolSpecs(binary) {
  const tmpHome = fs.mkdtempSync(path.join(os.tmpdir(), 'legion-tools-doc-'));
  try {
    const env = { ...process.env, LEGION_HOME: tmpHome };
    delete env.XDG_CONFIG_HOME;
    delete env.XDG_STATE_HOME;
    const run = spawnSync(binary, ['tools', '--json'], {
      encoding: 'utf8',
      env,
      maxBuffer: 32 * 1024 * 1024,
    });
    if (run.error) {
      throw new Error(`Could not run ${binary}: ${run.error.message}`);
    }
    if (run.status !== 0) {
      const detail = (run.stderr || run.stdout || `exit ${run.status}`).trim();
      throw new Error(`${binary} tools --json failed: ${detail}`);
    }
    const parsed = JSON.parse(run.stdout);
    if (!parsed || !Array.isArray(parsed.tools)) {
      throw new Error(`${binary} tools --json did not return a {"tools": [...]} object.`);
    }
    return parsed.tools;
  } finally {
    fs.rmSync(tmpHome, { recursive: true, force: true });
  }
}

/** First sentence or first line of a tool description, matching MCP catalog summaries. */
function firstSentence(text) {
  const line = String(text ?? '').split(/\r?\n/, 1)[0].trim();
  const dot = line.indexOf('. ');
  return dot >= 0 ? line.slice(0, dot + 1) : line;
}

/** Escape text for a single Markdown table cell. */
function cell(text) {
  return String(text ?? '')
    .replace(/\r?\n+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\|/g, '\\|');
}

/** Format a JSON Schema property type cleanly. */
function formatType(prop) {
  if (!prop || typeof prop !== 'object') return 'any';
  const raw = prop.type;
  const base = Array.isArray(raw)
    ? raw.filter(t => t !== 'null').join(' | ') || 'null'
    : (raw ?? 'any');
  if (base === 'array' && prop.items && typeof prop.items === 'object') {
    return `array of ${formatType(prop.items)}`;
  }
  return base;
}

/** Format a property's default value, or `-` when absent. */
function formatDefault(prop) {
  if (!prop || !Object.prototype.hasOwnProperty.call(prop, 'default')) return '-';
  return `\`${cell(JSON.stringify(prop.default))}\``;
}

/** Format a property's description, appending allowed enum values and bounds when present. */
function formatArgDescription(prop) {
  const parts = [];
  if (prop?.description) parts.push(cell(prop.description));
  if (Array.isArray(prop?.enum) && prop.enum.length > 0) {
    const values = prop.enum.map(v => `\`${cell(String(v))}\``).join(', ');
    parts.push(`Allowed values: ${values}.`);
  }
  const hasMin = typeof prop?.minimum === 'number';
  const hasMax = typeof prop?.maximum === 'number';
  if (hasMin && hasMax) {
    parts.push(`Range: ${prop.minimum} to ${prop.maximum}.`);
  } else if (hasMin) {
    parts.push(`Minimum: ${prop.minimum}.`);
  } else if (hasMax) {
    parts.push(`Maximum: ${prop.maximum}.`);
  }
  return parts.join(' ') || '-';
}

/** Render the Markdown body below the marker from an array of tool specs. */
export function renderToolsBody(tools) {
  const sorted = [...tools].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const families = new Map();
  for (const spec of sorted) {
    const family = spec.name.split('.', 1)[0];
    if (!families.has(family)) families.set(family, []);
    families.get(family).push(spec);
  }

  const out = [];
  const familyNames = [...families.keys()].sort();
  out.push(`Families (${familyNames.length}, ${sorted.length} tools total): ${familyNames.map(f => `[\`${f}\`](#${f})`).join(', ')}.`);
  out.push('');

  for (const family of familyNames) {
    const list = families.get(family);
    out.push(`## ${family}`);
    out.push('');
    out.push('| Tool | Effect | Description |');
    out.push('| --- | --- | --- |');
    for (const spec of list) {
      out.push(`| \`${spec.name}\` | \`${spec.effect}\` | ${cell(firstSentence(spec.description))} |`);
    }
    out.push('');

    for (const spec of list) {
      out.push(`### \`${spec.name}\``);
      out.push('');
      out.push(`Effect: \`${spec.effect}\``);
      out.push('');
      out.push(String(spec.description ?? '').trim());
      out.push('');

      const schema = spec.input_schema ?? {};
      const props = schema.properties && typeof schema.properties === 'object' ? schema.properties : {};
      const required = new Set(Array.isArray(schema.required) ? schema.required : []);
      const names = Object.keys(props);
      if (names.length === 0) {
        out.push('Takes no arguments.');
        out.push('');
      } else {
        out.push('| Argument | Type | Required | Default | Description |');
        out.push('| --- | --- | --- | --- | --- |');
        for (const argName of names) {
          const prop = props[argName];
          const typeStr = `\`${cell(formatType(prop))}\``;
          const reqStr = required.has(argName) ? 'yes' : 'no';
          const defStr = formatDefault(prop);
          const descStr = formatArgDescription(prop);
          out.push(`| \`${argName}\` | ${typeStr} | ${reqStr} | ${defStr} | ${descStr} |`);
        }
        out.push('');
      }
    }
  }

  return `${out.join('\n').trimEnd()}\n`;
}

/** Combine the hand-written header up to MARKER with the freshly rendered body. */
export function buildDocument(existingText, tools) {
  let header;
  if (existingText !== null) {
    const normalized = existingText.replace(/\r\n/g, '\n');
    const idx = normalized.indexOf(MARKER);
    if (idx === -1) {
      throw new Error(`Marker line not found in output file: ${MARKER}`);
    }
    header = `${normalized.slice(0, idx + MARKER.length)}\n\n`;
  } else {
    header = `${DEFAULT_INTRO}\n`;
  }
  return `${header}${renderToolsBody(tools)}`;
}

function parseCli(argv) {
  let check = false;
  let bin = null;
  let out = DEFAULT_OUT;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check') {
      check = true;
    } else if (arg === '--bin') {
      if (i + 1 >= argv.length) throw new Error('--bin requires a path.');
      bin = argv[++i];
    } else if (arg.startsWith('--bin=')) {
      bin = arg.slice('--bin='.length);
    } else if (arg === '--out') {
      if (i + 1 >= argv.length) throw new Error('--out requires a path.');
      out = path.resolve(argv[++i]);
    } else if (arg.startsWith('--out=')) {
      out = path.resolve(arg.slice('--out='.length));
    } else if (arg === '-h' || arg === '--help') {
      console.log('Usage: node scripts/legion-tools-doc.mjs [--bin <path>] [--out <path>] [--check]');
      process.exit(0);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return { check, bin, out };
}

const real = (file) => { try { return fs.realpathSync(file); } catch { return path.resolve(file); } };
if (process.argv[1] && real(process.argv[1]) === real(fileURLToPath(import.meta.url))) {
  let options;
  try {
    options = parseCli(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exit(2);
  }
  try {
    const binary = resolveBinary(repository, options.bin);
    const tools = readToolSpecs(binary);
    const existing = fs.existsSync(options.out) ? fs.readFileSync(options.out, 'utf8') : null;
    const expected = buildDocument(existing, tools);
    if (options.check) {
      const current = existing === null ? null : existing.replace(/\r\n/g, '\n');
      if (current !== expected) {
        console.error(`${path.relative(repository, options.out)} is out of date with ${path.relative(repository, binary)}.`);
        console.error('Run `node scripts/legion-tools-doc.mjs` and commit the updated file.');
        process.exit(1);
      }
      console.log(`${path.relative(repository, options.out)} matches ${tools.length} tools from ${path.relative(repository, binary)}.`);
    } else {
      fs.mkdirSync(path.dirname(options.out), { recursive: true });
      fs.writeFileSync(options.out, expected, 'utf8');
      console.log(`Wrote ${path.relative(repository, options.out)} (${tools.length} tools).`);
    }
  } catch (error) {
    console.error(error.message);
    process.exit(2);
  }
}
