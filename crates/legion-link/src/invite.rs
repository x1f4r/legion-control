//! Pairing invites and client-side device enrolment.
//!
//! An invite is a single text token printed by `legion pair --as <principal>` (also encoded in a
//! QR code): `legion-invite-1.` followed by unpadded base64url of a JSON object carrying the
//! node's name, reachable hosts, SSH port, account, pinned host keys, a 32-byte temporary Ed25519
//! seed, the principal being paired, and an expiry timestamp.

use std::collections::BTreeMap;
use std::fmt;
use std::str::FromStr;
use std::time::Duration;

use base64::Engine;
use base64::engine::general_purpose::{STANDARD, URL_SAFE_NO_PAD};
use jiff::Timestamp;
use legion_proto::{ErrorBody, ErrorCode};
use serde::{Deserialize, Serialize};
use zeroize::{Zeroize, Zeroizing};

/// Prefix of version 1 invite strings.
pub const INVITE_PREFIX: &str = "legion-invite-1.";
/// Supported invite payload version.
pub const INVITE_VERSION: u32 = 1;
/// Maximum byte length accepted for raw invite text before decoding (16 KiB).
pub const MAX_INVITE_LEN: usize = 16 * 1024;
/// Maximum byte length of identifier and host fields inside an invite.
const MAX_FIELD_LEN: usize = 255;
/// Maximum number of hosts listed in one invite.
const MAX_HOSTS: usize = 32;
/// Maximum number of host keys listed in one invite.
const MAX_HOST_KEYS: usize = 32;
/// Maximum byte length of a single OpenSSH public host key line.
const MAX_HOST_KEY_LEN: usize = 4096;

/// Pinned SSH connection target for a paired node.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct SshTarget {
    /// Host names or IP addresses tried in order when opening a connection.
    pub hosts: Vec<String>,
    /// SSH TCP port (normally 22).
    pub port: u16,
    /// Remote user account to authenticate as.
    pub user: String,
    /// OpenSSH public key lines pinned for this node (no trust on first use).
    pub host_keys: Vec<String>,
}

/// Default timeout waiting for a node to confirm device enrolment after the request is sent.
///
/// Enrolment persists `policy.toml`, `devices.toml`, and `authorized_keys` and then pushes
/// `devices.toml` to reachable fleet peers before replying, so it can legitimately take longer
/// than a routine `hello` handshake on slow links or loaded hosts.
pub const DEFAULT_ENROL_TIMEOUT: Duration = Duration::from_secs(45);

/// Timeouts and keepalive settings for connecting to a node.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SshTimeouts {
    /// Per-host TCP connect + SSH handshake + auth timeout.
    pub connect: Duration,
    /// Timeout for the Legion `hello` handshake and live `hello` probes.
    pub handshake: Duration,
    /// Timeout waiting for a node to confirm device enrolment after the request is sent.
    pub enrol: Duration,
    /// Interval between SSH keepalive probes when the connection is quiet (`None` disables).
    pub keepalive_interval: Option<Duration>,
    /// Number of unanswered keepalives before closing the connection.
    pub keepalive_max: usize,
}

impl Default for SshTimeouts {
    fn default() -> Self {
        SshTimeouts {
            connect: Duration::from_secs(10),
            handshake: Duration::from_secs(10),
            enrol: DEFAULT_ENROL_TIMEOUT,
            keepalive_interval: Some(Duration::from_secs(15)),
            keepalive_max: 3,
        }
    }
}

/// Parsed pairing invite produced by `legion pair` / `device.invite`.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Invite {
    /// Format version (must be [`INVITE_VERSION`]).
    pub v: u32,
    /// Unique invite identifier generated by the node.
    pub id: String,
    /// Name of the node being paired.
    pub node: String,
    /// Host names or IP addresses the controller tries in order.
    pub hosts: Vec<String>,
    /// SSH TCP port on the node.
    pub port: u16,
    /// Remote user account on the node.
    pub user: String,
    /// Pinned OpenSSH public host key lines for the node.
    pub host_keys: Vec<String>,
    /// Standard base64 encoding of the 32-byte Ed25519 seed of the temporary invite key.
    pub key: String,
    /// Principal the enrolled device will act as.
    pub principal: String,
    /// RFC 3339 UTC expiry timestamp; enforced by the node, not rejected client-side.
    pub expires: String,
}

impl fmt::Debug for Invite {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Invite")
            .field("v", &self.v)
            .field("id", &self.id)
            .field("node", &self.node)
            .field("hosts", &self.hosts)
            .field("port", &self.port)
            .field("user", &self.user)
            .field("host_keys", &self.host_keys)
            .field("key", &"<redacted>")
            .field("principal", &self.principal)
            .field("expires", &self.expires)
            .finish()
    }
}

impl Invite {
    /// Parses a `legion-invite-1.<base64url>` invite string.
    ///
    /// Unknown JSON fields are ignored for forward compatibility. Expiry is NOT rejected
    /// client-side because clocks can skew and the node's sshd/enrolment handler is authoritative.
    pub fn parse(text: &str) -> Result<Self, ErrorBody> {
        let trimmed = text.trim();
        if trimmed.len() > MAX_INVITE_LEN {
            return Err(ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!(
                    "Invite text is too large ({} bytes; maximum is {MAX_INVITE_LEN} bytes).",
                    trimmed.len()
                ),
            )
            .with_hint("Paste only the single invite string printed by `legion pair`."));
        }
        let Some(encoded) = trimmed.strip_prefix(INVITE_PREFIX) else {
            if let Some(rest) = trimmed.strip_prefix("legion-invite-")
                && let Some((ver, _)) = rest.split_once('.')
            {
                return Err(ErrorBody::new(
                    ErrorCode::Unsupported,
                    format!("Invite version {ver:?} is not supported (expected version {INVITE_VERSION})."),
                )
                .with_hint("Update the app or generate a new invite from a compatible legion node."));
            }
            return Err(ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite must begin with `{INVITE_PREFIX}`."),
            )
            .with_hint("Copy the full invite text or scan the QR code printed by `legion pair`."));
        };
        if encoded.is_empty() {
            return Err(
                ErrorBody::new(ErrorCode::InvalidArgs, "Invite payload is empty.")
                    .with_hint("Copy the full invite text printed by `legion pair`."),
            );
        }
        let bytes = URL_SAFE_NO_PAD.decode(encoded).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite payload is not valid unpadded base64url: {err}."),
            )
            .with_hint("Check that the invite was not truncated or altered when copied.")
        })?;
        let raw_value: serde_json::Value = serde_json::from_slice(&bytes).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite payload is not valid JSON: {err}."),
            )
            .with_hint("Generate a fresh invite with `legion pair`.")
        })?;
        if let Some(v) = raw_value.get("v").and_then(serde_json::Value::as_u64)
            && v != u64::from(INVITE_VERSION)
        {
            return Err(ErrorBody::new(
                ErrorCode::Unsupported,
                format!("Invite version {v} is not supported (expected version {INVITE_VERSION})."),
            )
            .with_hint("Update the app or generate a new invite from a compatible legion node."));
        }
        let invite: Invite = serde_json::from_value(raw_value).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite is missing required fields or has invalid field types: {err}."),
            )
            .with_hint("Generate a fresh invite with `legion pair`.")
        })?;
        invite.validate()?;
        Ok(invite)
    }

    /// Encodes this invite back into its `legion-invite-1.<base64url>` text form.
    pub fn encode(&self) -> Result<String, ErrorBody> {
        self.validate()?;
        let json = serde_json::to_vec(self).map_err(|err| {
            ErrorBody::new(
                ErrorCode::Internal,
                format!("Could not serialize invite: {err}."),
            )
        })?;
        Ok(format!("{INVITE_PREFIX}{}", URL_SAFE_NO_PAD.encode(json)))
    }

    /// Extracts the 32-byte Ed25519 seed of the temporary enrolment key, zeroizing the
    /// intermediate decode buffer and wrapping the returned seed in [`Zeroizing`].
    pub fn key_seed(&self) -> Result<Zeroizing<[u8; 32]>, ErrorBody> {
        let mut raw = STANDARD.decode(self.key.trim()).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite temporary key is not valid base64: {err}."),
            )
            .with_hint("Generate a fresh invite with `legion pair`.")
        })?;
        let res = <[u8; 32]>::try_from(raw.as_slice())
            .map(Zeroizing::new)
            .map_err(|_| {
                ErrorBody::new(
                    ErrorCode::InvalidArgs,
                    format!(
                        "Invite temporary key must decode to 32 bytes, got {}.",
                        raw.len()
                    ),
                )
                .with_hint("Generate a fresh invite with `legion pair`.")
            });
        raw.zeroize();
        res
    }

    /// Returns the pinned [`SshTarget`] carried by this invite.
    pub fn target(&self) -> SshTarget {
        SshTarget {
            hosts: self.hosts.clone(),
            port: self.port,
            user: self.user.clone(),
            host_keys: self.host_keys.clone(),
        }
    }

    fn validate(&self) -> Result<(), ErrorBody> {
        if self.v != INVITE_VERSION {
            return Err(ErrorBody::new(
                ErrorCode::Unsupported,
                format!(
                    "Invite version {} is not supported (expected version {INVITE_VERSION}).",
                    self.v
                ),
            )
            .with_hint("Update the app or generate a new invite from a compatible legion node."));
        }
        validate_token_field("id", &self.id)?;
        validate_token_field("node", &self.node)?;
        validate_token_field("user", &self.user)?;
        validate_token_field("principal", &self.principal)?;
        if self.hosts.is_empty() {
            return Err(missing_field("hosts"));
        }
        if self.hosts.len() > MAX_HOSTS {
            return Err(ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!(
                    "Invite lists too many hosts ({}; maximum is {MAX_HOSTS}).",
                    self.hosts.len()
                ),
            )
            .with_hint("Generate a fresh invite with `legion pair`."));
        }
        for host in &self.hosts {
            validate_token_field("hosts", host)?;
        }
        if self.port == 0 {
            return Err(
                ErrorBody::new(ErrorCode::InvalidArgs, "Invite port cannot be zero.")
                    .with_hint("Generate a fresh invite with `legion pair`."),
            );
        }
        if self.host_keys.is_empty() {
            return Err(missing_field("host_keys"));
        }
        if self.host_keys.len() > MAX_HOST_KEYS {
            return Err(ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!(
                    "Invite lists too many host keys ({}; maximum is {MAX_HOST_KEYS}).",
                    self.host_keys.len()
                ),
            )
            .with_hint("Generate a fresh invite with `legion pair`."));
        }
        for (index, key_line) in self.host_keys.iter().enumerate() {
            validate_openssh_public_key_line(index, key_line)?;
        }
        if self.expires.trim().is_empty() {
            return Err(missing_field("expires"));
        }
        Timestamp::from_str(&self.expires).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite field `expires` is not a valid RFC 3339 timestamp: {err}."),
            )
            .with_hint("Generate a fresh invite with `legion pair`.")
        })?;
        let _ = self.key_seed()?;
        Ok(())
    }
}

pub(crate) fn validate_token_field(field: &str, value: &str) -> Result<(), ErrorBody> {
    if value.is_empty() {
        return Err(missing_field(field));
    }
    if value.len() > MAX_FIELD_LEN {
        return Err(ErrorBody::new(
            ErrorCode::InvalidArgs,
            format!(
                "Invite field `{field}` is too long ({} bytes; maximum is {MAX_FIELD_LEN}).",
                value.len()
            ),
        )
        .with_hint("Generate a fresh invite with `legion pair`."));
    }
    if value.starts_with('-') {
        return Err(ErrorBody::new(
            ErrorCode::InvalidArgs,
            format!("Invite field `{field}` cannot begin with `-`."),
        )
        .with_hint("Generate a fresh invite with `legion pair`."));
    }
    if value.chars().any(|c| c.is_control() || c.is_whitespace()) {
        return Err(ErrorBody::new(
            ErrorCode::InvalidArgs,
            format!("Invite field `{field}` cannot contain whitespace or control characters."),
        )
        .with_hint("Generate a fresh invite with `legion pair`."));
    }
    Ok(())
}

pub(crate) fn validate_openssh_public_key_line(index: usize, line: &str) -> Result<(), ErrorBody> {
    if line.len() > MAX_HOST_KEY_LEN {
        return Err(ErrorBody::new(
            ErrorCode::InvalidArgs,
            format!("Invite host key #{index} exceeds {MAX_HOST_KEY_LEN} bytes."),
        )
        .with_hint("Generate a fresh invite with `legion pair`."));
    }
    if line.chars().any(|c| c.is_control()) {
        return Err(ErrorBody::new(
            ErrorCode::InvalidArgs,
            format!("Invite host key #{index} cannot contain control characters."),
        )
        .with_hint("Use single-line OpenSSH public keys such as `ssh-ed25519 AAAA...`."));
    }
    let trimmed = line.trim();
    if trimmed.is_empty() {
        return Err(missing_field("host_keys"));
    }
    #[cfg(feature = "ssh")]
    {
        russh::keys::PublicKey::from_openssh(trimmed).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite host key #{index} is not a valid OpenSSH public key: {err}."),
            )
            .with_hint("Use OpenSSH public key lines such as `ssh-ed25519 AAAA...`.")
        })?;
        Ok(())
    }
    #[cfg(not(feature = "ssh"))]
    {
        let mut parts = trimmed.split_whitespace();
        let Some(algo) = parts.next() else {
            return Err(missing_field("host_keys"));
        };
        let Some(blob_b64) = parts.next() else {
            return Err(ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite host key #{index} is missing its base64 key blob."),
            )
            .with_hint("Use OpenSSH public key lines such as `ssh-ed25519 AAAA...`."));
        };
        let blob = STANDARD.decode(blob_b64).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite host key #{index} has invalid base64: {err}."),
            )
            .with_hint("Use OpenSSH public key lines such as `ssh-ed25519 AAAA...`.")
        })?;
        // RFC 4253 key blobs begin with a big-endian u32 length-prefixed algorithm identifier.
        if blob.len() < 4 {
            return Err(ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite host key #{index} blob is truncated."),
            )
            .with_hint("Use OpenSSH public key lines such as `ssh-ed25519 AAAA...`."));
        }
        let alg_len = u32::from_be_bytes([blob[0], blob[1], blob[2], blob[3]]) as usize;
        if blob.len() <= 4 + alg_len || &blob[4..4 + alg_len] != algo.as_bytes() {
            return Err(ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!(
                    "Invite host key #{index} blob does not match its declared algorithm `{algo}`."
                ),
            )
            .with_hint("Use OpenSSH public key lines such as `ssh-ed25519 AAAA...`."));
        }
        Ok(())
    }
}

fn missing_field(field: &str) -> ErrorBody {
    ErrorBody::new(
        ErrorCode::InvalidArgs,
        format!("Invite field `{field}` cannot be empty."),
    )
    .with_hint("Generate a fresh invite with `legion pair`.")
}

/// Per-machine sync outcome returned in the enrolment reply's `fleet` map.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct FleetPushOutcome {
    /// `"synced"` when the peer accepted the new device, or `"not_reached"` when it could not be
    /// reached or returned an error.
    pub status: String,
    /// Human-readable reason when `status` is `"not_reached"`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
}

fn is_false(value: &bool) -> bool {
    !*value
}

/// Information returned by a node when enrolment succeeds, carrying everything needed to reconnect
/// later using the permanent device key.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Enrolled {
    /// Node name confirmed by the node.
    pub node: String,
    /// Pinned SSH connection target to reach this node.
    pub target: SshTarget,
    /// Principal this device is bound to on the node.
    pub principal: String,
    /// Role assigned to that principal on the node.
    pub role: String,
    /// Device name as stored by the node.
    pub device: String,
    /// Per-machine sync outcome when the node pushed this device to peers in `fleet.toml`.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub fleet: BTreeMap<String, FleetPushOutcome>,
    /// Fleet machines that did not receive this device yet during enrolment.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub not_synced_to: Vec<String>,
    /// Exact sync command reported by the node when `not_synced_to` is non-empty.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sync_command: Option<String>,
    /// `true` when this pairing was confirmed via the pinned-key recovery probe rather than the
    /// direct enrolment reply line (so `fleet` / `not_synced_to` were not returned by the node).
    #[serde(default, skip_serializing_if = "is_false")]
    pub recovered: bool,
}

