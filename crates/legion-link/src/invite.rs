        assert_eq!(
            unreach_err.details.as_ref().unwrap()[crate::DETAIL_SENT],
            json!(true)
        );
        assert_eq!(
            unreach_err.details.as_ref().unwrap()["outcome"],
            json!("uncertain")
        );

