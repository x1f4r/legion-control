//! Pairing invites and client-side device enrolment.
//!
//! An invite is a single text token printed by `legion pair --as <principal>` (also encoded in a
//! QR code): `legion-invite-1.` followed by unpadded base64url of a JSON object carrying the
//! node's name, reachable hosts, SSH port, account, pinned host keys, a 32-byte temporary Ed25519
//! seed, the principal being paired, and an expiry timestamp.

use base64::Engine;
use base64::engine::general_purpose::{STANDARD, URL_SAFE_NO_PAD};
use legion_proto::{ErrorBody, ErrorCode};
use serde::{Deserialize, Serialize};

/// Prefix of version 1 invite strings.
pub const INVITE_PREFIX: &str = "legion-invite-1.";
/// Supported invite payload version.
pub const INVITE_VERSION: u32 = 1;

/// Pinned SSH connection target for a paired node.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct SshTarget {
    /// Host names or IP addresses tried in order when opening a connection.
    pub hosts: Vec<String>,
    /// SSH TCP port (normally 22).
    pub port: u16,
    /// Remote user account to authenticate as.
    pub user: String,
    /// OpenSSH public key lines pinned for this node (no trust on first use).
    pub host_keys: Vec<String>,
}

/// Parsed pairing invite produced by `legion pair` / `device.invite`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Invite {
    /// Format version (must be [`INVITE_VERSION`]).
    pub v: u32,
    /// Unique invite identifier generated by the node.
    pub id: String,
    /// Name of the node being paired.
    pub node: String,
    /// Host names or IP addresses the controller tries in order.
    pub hosts: Vec<String>,
    /// SSH TCP port on the node.
    pub port: u16,
    /// Remote user account on the node.
    pub user: String,
    /// Pinned OpenSSH public host key lines for the node.
    pub host_keys: Vec<String>,
    /// Standard base64 encoding of the 32-byte Ed25519 seed of the temporary invite key.
    pub key: String,
    /// Principal the enrolled device will act as.
    pub principal: String,
    /// RFC 3339 UTC expiry timestamp; enforced by the node, not rejected client-side.
    pub expires: String,
}

impl Invite {
    /// Parses a `legion-invite-1.<base64url>` invite string.
    ///
    /// Unknown JSON fields are ignored for forward compatibility. Expiry is NOT rejected
    /// client-side because clocks can skew and the node's sshd/enrolment handler is authoritative.
    pub fn parse(text: &str) -> Result<Self, ErrorBody> {
        let trimmed = text.trim();
        let Some(encoded) = trimmed.strip_prefix(INVITE_PREFIX) else {
            if let Some(rest) = trimmed.strip_prefix("legion-invite-")
                && let Some((ver, _)) = rest.split_once('.')
            {
                return Err(ErrorBody::new(
                    ErrorCode::Unsupported,
                    format!("Invite version {ver:?} is not supported (expected version {INVITE_VERSION})."),
                )
                .with_hint("Update the app or generate a new invite from a compatible legion node."));
            }
            return Err(ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite must begin with `{INVITE_PREFIX}`."),
            )
            .with_hint("Copy the full invite text or scan the QR code printed by `legion pair`."));
        };
        if encoded.is_empty() {
            return Err(
                ErrorBody::new(ErrorCode::InvalidArgs, "Invite payload is empty.")
                    .with_hint("Copy the full invite text printed by `legion pair`."),
            );
        }
        let bytes = URL_SAFE_NO_PAD.decode(encoded).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite payload is not valid unpadded base64url: {err}."),
            )
            .with_hint("Check that the invite was not truncated or altered when copied.")
        })?;
        let raw_value: serde_json::Value = serde_json::from_slice(&bytes).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite payload is not valid JSON: {err}."),
            )
            .with_hint("Generate a fresh invite with `legion pair`.")
        })?;
        if let Some(v) = raw_value.get("v").and_then(serde_json::Value::as_u64)
            && v != u64::from(INVITE_VERSION)
        {
            return Err(ErrorBody::new(
                ErrorCode::Unsupported,
                format!("Invite version {v} is not supported (expected version {INVITE_VERSION})."),
            )
            .with_hint("Update the app or generate a new invite from a compatible legion node."));
        }
        let invite: Invite = serde_json::from_value(raw_value).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite is missing required fields or has invalid field types: {err}."),
            )
            .with_hint("Generate a fresh invite with `legion pair`.")
        })?;
        invite.validate()?;
        Ok(invite)
    }

    /// Encodes this invite back into its `legion-invite-1.<base64url>` text form.
    pub fn encode(&self) -> Result<String, ErrorBody> {
        self.validate()?;
        let json = serde_json::to_vec(self).map_err(|err| {
            ErrorBody::new(
                ErrorCode::Internal,
                format!("Could not serialize invite: {err}."),
            )
        })?;
        Ok(format!("{INVITE_PREFIX}{}", URL_SAFE_NO_PAD.encode(json)))
    }

    /// Extracts the 32-byte Ed25519 seed of the temporary enrolment key.
    pub fn key_seed(&self) -> Result<[u8; 32], ErrorBody> {
        let raw = STANDARD.decode(self.key.trim()).map_err(|err| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!("Invite temporary key is not valid base64: {err}."),
            )
            .with_hint("Generate a fresh invite with `legion pair`.")
        })?;
        <[u8; 32]>::try_from(raw.as_slice()).map_err(|_| {
            ErrorBody::new(
                ErrorCode::InvalidArgs,
                format!(
                    "Invite temporary key must decode to 32 bytes, got {}.",
                    raw.len()
                ),
            )
            .with_hint("Generate a fresh invite with `legion pair`.")
        })
    }

    /// Returns the pinned [`SshTarget`] carried by this invite.
    pub fn target(&self) -> SshTarget {
        SshTarget {
            hosts: self.hosts.clone(),
            port: self.port,
            user: self.user.clone(),
            host_keys: self.host_keys.clone(),
        }
    }

    fn validate(&self) -> Result<(), ErrorBody> {
        if self.v != INVITE_VERSION {
            return Err(ErrorBody::new(
                ErrorCode::Unsupported,
                format!(
                    "Invite version {} is not supported (expected version {INVITE_VERSION}).",
                    self.v
                ),
            )
            .with_hint("Update the app or generate a new invite from a compatible legion node."));
        }
        if self.id.trim().is_empty() {
            return Err(missing_field("id"));
        }
        if self.node.trim().is_empty() {
            return Err(missing_field("node"));
        }
        if self.hosts.is_empty() || self.hosts.iter().any(|h| h.trim().is_empty()) {
            return Err(missing_field("hosts"));
        }
        if self.port == 0 {
            return Err(
                ErrorBody::new(ErrorCode::InvalidArgs, "Invite port cannot be zero.")
                    .with_hint("Generate a fresh invite with `legion pair`."),
            );
        }
        if self.user.trim().is_empty() {
            return Err(missing_field("user"));
        }
        if self.host_keys.is_empty() || self.host_keys.iter().any(|k| k.trim().is_empty()) {
            return Err(missing_field("host_keys"));
        }
        if self.principal.trim().is_empty() {
            return Err(missing_field("principal"));
        }
        if self.expires.trim().is_empty() {
            return Err(missing_field("expires"));
        }
        let _ = self.key_seed()?;
        Ok(())
    }
}

fn missing_field(field: &str) -> ErrorBody {
    ErrorBody::new(
        ErrorCode::InvalidArgs,
        format!("Invite field `{field}` cannot be empty."),
    )
    .with_hint("Generate a fresh invite with `legion pair`.")
}

/// Information returned by a node when enrolment succeeds, carrying everything needed to reconnect
/// later using the permanent device key.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Enrolled {
    /// Node name confirmed by the node.
    pub node: String,
    /// Pinned SSH connection target to reach this node.
    pub target: SshTarget,
    /// Principal this device is bound to on the node.
    pub principal: String,
    /// Role assigned to that principal on the node.
    pub role: String,
    /// Device name as stored by the node.
    pub device: String,
}

#[cfg(feature = "ssh")]
pub use self::enrol_client::enrol;

#[cfg(feature = "ssh")]
mod enrol_client {
    use std::time::Duration;

    use legion_proto::{ErrorBody, ErrorCode};
    use serde::{Deserialize, Serialize};
    use serde_json::Value;
    use tokio::io::{AsyncWriteExt, BufReader};
    use tokio_util::sync::CancellationToken;

    use super::{Enrolled, Invite};
    use crate::key::DeviceKey;
    use crate::session::{Line, TransportHandle, read_line};
    use crate::ssh::{SshTimeouts, open_exec_raw};

    const ENROL_COMMAND: &str = "legion enrol";
    const MAX_REPLY_LINE: usize = 64 * 1024;
    const MAX_NOISE_LINES: usize = 32;
    const CLOSE_GRACE: Duration = Duration::from_millis(500);

    #[derive(Serialize)]
    struct EnrolRequest<'a> {
        enrol: u32,
        id: &'a str,
        public_key: &'a str,
        name: &'a str,
    }

    #[derive(Deserialize)]
    struct EnrolResponse {
        ok: bool,
        #[serde(default)]
        node: Option<String>,
        #[serde(default)]
        principal: Option<String>,
        #[serde(default)]
        role: Option<String>,
        #[serde(default)]
        device: Option<String>,
        #[serde(default)]
        error: Option<Value>,
    }

    /// Enrols `device_key` on the node described by `invite` under `device_name`.
    ///
    /// Connects with the invite's temporary key and pinned host keys, requests the literal command
    /// `legion enrol` (which the node's forced command ignores), exchanges the one-line JSON
    /// enrolment handshake, and returns [`Enrolled`] with everything needed to reconnect later.
    pub async fn enrol(
        invite: &Invite,
        device_key: &DeviceKey,
        device_name: &str,
        timeouts: SshTimeouts,
        cancel: CancellationToken,
    ) -> Result<Enrolled, ErrorBody> {
        let name = device_name.trim();
        if name.is_empty() || name.chars().any(|c| c.is_control()) {
            return Err(ErrorBody::new(
                ErrorCode::InvalidArgs,
                "Device name must be a non-empty single-line string.",
            )
            .with_hint("Pass a short label such as `phone` or `tablet`."));
        }
        let temp_key = DeviceKey::from_seed(invite.key_seed()?);
        let target = invite.target();
        let public_key = device_key.public_key_line(name)?;

        let pipe = open_exec_raw(&target, &temp_key, ENROL_COMMAND, timeouts, cancel.clone())
            .await
            .map_err(|err| {
                // If authentication failed using the invite's temporary key, note the invite's
                // expiry timestamp so the user knows it may have expired or already been used.
                if err
                    .details
                    .as_ref()
                    .and_then(|d| d.get("reason"))
                    .and_then(Value::as_str)
                    == Some(crate::ssh::REASON_AUTH_FAILED)
                {
                    err.with_hint(format!(
                        "The invite key was rejected; invites are single-use and this invite expires at {}. Generate a fresh invite with `legion pair`.",
                        invite.expires
                    ))
                } else {
                    err
                }
            })?;

        let (reader, mut writer, mut handle) = pipe.into_parts();
        let stderr = handle.stderr_tail();

        let req = EnrolRequest {
            enrol: 1,
            id: &invite.id,
            public_key: &public_key,
            name,
        };
        let mut line = serde_json::to_string(&req).map_err(|err| {
            ErrorBody::new(
                ErrorCode::Internal,
                format!("Could not encode enrolment request: {err}."),
            )
        })?;
        line.push('\n');

        let exchange = async {
            writer.write_all(line.as_bytes()).await.map_err(|err| {
                ErrorBody::new(
                    ErrorCode::Unreachable,
                    format!(
                        "Could not send enrolment request to {}: {err}.",
                        invite.node
                    ),
                )
            })?;
            writer.flush().await.map_err(|err| {
                ErrorBody::new(
                    ErrorCode::Unreachable,
                    format!(
                        "Could not flush enrolment request to {}: {err}.",
                        invite.node
                    ),
                )
            })?;

            let mut buf_reader = BufReader::new(reader);
            let mut reply_buf = Vec::new();
            let mut noise = 0usize;
            loop {
                match read_line(&mut buf_reader, &mut reply_buf, MAX_REPLY_LINE).await {
                    Ok(Line::End) => {
                        let (_, stderr_text) =
                            handle.collect_exit_info(Duration::from_millis(200)).await;
                        let mut err = ErrorBody::new(
                            ErrorCode::Unreachable,
                            format!(
                                "{} closed the connection before answering the enrolment request.",
                                invite.node
                            ),
                        )
                        .with_machine(&invite.node);
                        if !stderr_text.is_empty() {
                            err = err.with_hint(format!("Remote stderr: {stderr_text}"));
                        } else {
                            err = err.with_hint(format!(
                                "Check that the invite (expires {}) has not expired or already been used.",
                                invite.expires
                            ));
                        }
                        return Err(err);
                    }
                    Ok(Line::TooLong) => {
                        return Err(ErrorBody::new(
                            ErrorCode::Failed,
                            format!("{} sent an oversized enrolment reply.", invite.node),
                        )
                        .with_machine(&invite.node));
                    }
                    Ok(Line::Read) => {
                        if reply_buf.iter().all(u8::is_ascii_whitespace) {
                            continue;
                        }
                        if let Ok(resp) = serde_json::from_slice::<EnrolResponse>(&reply_buf) {
                            return parse_enrol_response(resp, invite, target.clone());
                        }
                        noise += 1;
                        if noise > MAX_NOISE_LINES {
                            return Err(ErrorBody::new(
                                ErrorCode::Failed,
                                format!(
                                    "{} sent non-protocol output instead of an enrolment reply.",
                                    invite.node
                                ),
                            )
                            .with_machine(&invite.node)
                            .with_hint(
                                "Check that the invite key is bound to the node's enrolment command.",
                            ));
                        }
                    }
                    Err(err) => {
                        return Err(ErrorBody::new(
                            ErrorCode::Unreachable,
                            format!(
                                "Reading enrolment reply from {} failed: {err}.",
                                invite.node
                            ),
                        )
                        .with_machine(&invite.node));
                    }
                }
            }
        };

        let result = tokio::select! {
            biased;
            () = cancel.cancelled() => Err(ErrorBody::new(
                ErrorCode::Cancelled,
                format!("Enrolment with {} was cancelled.", invite.node),
            )
            .with_machine(&invite.node)),
            res = tokio::time::timeout(timeouts.handshake, exchange) => match res {
                Ok(outcome) => outcome,
                Err(_) => {
                    let mut err = ErrorBody::new(
                        ErrorCode::Timeout,
                        format!(
                            "Timed out waiting for {} to confirm enrolment after {}s.",
                            invite.node,
                            timeouts.handshake.as_secs_f64()
                        ),
                    )
                    .with_machine(&invite.node);
                    let text = stderr.text();
                    if !text.is_empty() {
                        err = err.with_hint(format!("Remote stderr: {text}"));
                    }
                    Err(err)
                }
            }
        };

        drop(writer);
        Box::new(handle).close(CLOSE_GRACE).await;
        result
    }

    fn parse_enrol_response(
        resp: EnrolResponse,
        invite: &Invite,
        target: super::SshTarget,
    ) -> Result<Enrolled, ErrorBody> {
        if resp.ok {
            let node = resp.node.unwrap_or_else(|| invite.node.clone());
            let principal = resp.principal.unwrap_or_else(|| invite.principal.clone());
            let role = resp.role.unwrap_or_default();
            let device = resp.device.unwrap_or_default();
            if role.is_empty() || device.is_empty() {
                return Err(ErrorBody::new(
                    ErrorCode::Failed,
                    format!("{node} sent an incomplete enrolment reply."),
                )
                .with_machine(&node));
            }
            return Ok(Enrolled {
                node,
                target,
                principal,
                role,
                device,
            });
        }

        if let Some(err_val) = resp.error {
            if let Ok(body) = serde_json::from_value::<ErrorBody>(err_val.clone()) {
                return Err(body.with_machine(&invite.node));
            }
            let message = err_val
                .get("message")
                .and_then(Value::as_str)
                .unwrap_or("Enrolment was rejected by the node.");
            let mut body = ErrorBody::new(ErrorCode::Failed, message).with_machine(&invite.node);
            if let Some(hint) = err_val.get("hint").and_then(Value::as_str) {
                body = body.with_hint(hint);
            }
            return Err(body);
        }

        Err(ErrorBody::new(
            ErrorCode::Failed,
            format!(
                "{} rejected enrolment without an error detail.",
                invite.node
            ),
        )
        .with_machine(&invite.node))
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]

    use serde_json::json;

    use super::*;

    fn sample_seed_b64() -> String {
        STANDARD.encode([7u8; 32])
    }

    fn sample_invite() -> Invite {
        Invite {
            v: 1,
            id: "inv-01".to_owned(),
            node: "tower".to_owned(),
            hosts: vec!["tower.example.net".to_owned(), "100.64.0.7".to_owned()],
            port: 22,
            user: "me".to_owned(),
            host_keys: vec!["ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIMockHostKey".to_owned()],
            key: sample_seed_b64(),
            principal: "phone".to_owned(),
            expires: "2026-11-24T12:00:00Z".to_owned(),
        }
    }

    #[test]
    fn parses_good_invite_and_ignores_unknown_fields() {
        let payload = json!({
            "v": 1,
            "id": "inv-01",
            "node": "tower",
            "hosts": ["tower.example.net", "100.64.0.7"],
            "port": 22,
            "user": "me",
            "host_keys": ["ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIMockHostKey"],
            "key": sample_seed_b64(),
            "principal": "phone",
            "expires": "2026-11-24T12:00:00Z",
            "future_extra_field": {"nested": true}
        });
        let text = format!(
            "  {INVITE_PREFIX}{}  \n",
            URL_SAFE_NO_PAD.encode(serde_json::to_vec(&payload).unwrap())
        );
        let parsed = Invite::parse(&text).unwrap();
        assert_eq!(parsed, sample_invite());
        assert_eq!(parsed.key_seed().unwrap(), [7u8; 32]);

        let reencoded = parsed.encode().unwrap();
        assert_eq!(Invite::parse(&reencoded).unwrap(), parsed);
    }

    #[test]
    fn rejects_wrong_prefix_or_version() {
        let err = Invite::parse("not-an-invite").unwrap_err();
        assert_eq!(err.code, ErrorCode::InvalidArgs);

        let err = Invite::parse("legion-invite-2.e30").unwrap_err();
        assert_eq!(err.code, ErrorCode::Unsupported);
        assert!(err.message.contains("2"), "{}", err.message);

        let wrong_v = json!({
            "v": 2,
            "id": "inv-01",
            "node": "tower",
            "hosts": ["tower.example.net"],
            "port": 22,
            "user": "me",
            "host_keys": ["ssh-ed25519 AAAA"],
            "key": sample_seed_b64(),
            "principal": "phone",
            "expires": "2026-11-24T12:00:00Z"
        });
        let text = format!(
            "{INVITE_PREFIX}{}",
            URL_SAFE_NO_PAD.encode(serde_json::to_vec(&wrong_v).unwrap())
        );
        let err = Invite::parse(&text).unwrap_err();
        assert_eq!(err.code, ErrorCode::Unsupported);
    }

    #[test]
    fn rejects_bad_base64_and_missing_or_empty_fields() {
        let err = Invite::parse("legion-invite-1.!!!not-base64!!!").unwrap_err();
        assert_eq!(err.code, ErrorCode::InvalidArgs);

        // Missing required field (`principal`).
        let missing = json!({
            "v": 1,
            "id": "inv-01",
            "node": "tower",
            "hosts": ["tower.example.net"],
            "port": 22,
            "user": "me",
            "host_keys": ["ssh-ed25519 AAAA"],
            "key": sample_seed_b64(),
            "expires": "2026-11-24T12:00:00Z"
        });
        let text = format!(
            "{INVITE_PREFIX}{}",
            URL_SAFE_NO_PAD.encode(serde_json::to_vec(&missing).unwrap())
        );
        let err = Invite::parse(&text).unwrap_err();
        assert_eq!(err.code, ErrorCode::InvalidArgs);

        // Wrong key length (not 32 bytes).
        let short_key = json!({
            "v": 1,
            "id": "inv-01",
            "node": "tower",
            "hosts": ["tower.example.net"],
            "port": 22,
            "user": "me",
            "host_keys": ["ssh-ed25519 AAAA"],
            "key": STANDARD.encode([1u8; 16]),
            "principal": "phone",
            "expires": "2026-11-24T12:00:00Z"
        });
        let text = format!(
            "{INVITE_PREFIX}{}",
            URL_SAFE_NO_PAD.encode(serde_json::to_vec(&short_key).unwrap())
        );
        let err = Invite::parse(&text).unwrap_err();
        assert_eq!(err.code, ErrorCode::InvalidArgs);
    }

    #[test]
    fn expired_invite_is_accepted_by_parser_so_node_decides() {
        let mut expired = sample_invite();
        expired.expires = "2020-01-01T00:00:00Z".to_owned();
        let text = expired.encode().unwrap();
        let parsed = Invite::parse(&text).unwrap();
        assert_eq!(parsed.expires, "2020-01-01T00:00:00Z");
    }
}
